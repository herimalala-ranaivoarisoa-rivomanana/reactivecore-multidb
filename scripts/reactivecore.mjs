#!/usr/bin/env node
import { createHash, randomUUID } from 'node:crypto';
import { spawn } from 'node:child_process';
import {
  cp,
  mkdir,
  readFile,
  readdir,
  rename,
  unlink,
  writeFile,
} from 'node:fs/promises';
import { basename, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const root = fileURLToPath(new URL('../', import.meta.url));
const template = join(root, 'scripts/project-template');
const format = /^[a-z][a-z0-9-]{0,39}$/;
const functionName = /^[a-z][a-z0-9_.-]{1,127}$/;
const uuid = /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i;
const generated = '// Generated by reactivecore codegen.\n';

function env(name) {
  const value = process.env[name];
  if (!value) throw new Error(`${name} is required`);
  return value;
}

function type(shape) {
  if (['string', 'number', 'boolean', 'null'].includes(shape)) return shape;
  if (Array.isArray(shape) && shape.length === 1)
    return `Array<${type(shape[0])}>`;
  if (Array.isArray(shape) && shape.length === 2 && shape[1] === 'null')
    return `${type(shape[0])} | null`;
  if (shape && typeof shape === 'object' && !Array.isArray(shape)) {
    const fields = Object.entries(shape).map(
      ([key, value]) => `${JSON.stringify(key)}: ${type(value)}`,
    );
    return fields.length ? `{ ${fields.join('; ')} }` : 'Record<string, never>';
  }
  throw new Error('Unsupported type in project.json');
}

async function codegen(directory, manifest) {
  function definitions(functions) {
    if (
      !functions ||
      typeof functions !== 'object' ||
      Array.isArray(functions)
    ) {
      throw new Error('Expected a function map in project.json');
    }
    return Object.entries(functions)
      .map(([name, definition]) => {
        if (!functionName.test(name))
          throw new Error(`Invalid function name: ${name}`);
        return `  ${JSON.stringify(name)}: { args: ${type(definition.args)}; result: ${type(definition.result)} };`;
      })
      .join('\n');
  }
  const output = join(directory, 'client.ts');
  const content = `${generated}import { ReactiveCoreClient } from '@reactivecore/client';

interface Queries {
${definitions(manifest.queries)}
}
interface Mutations {
${definitions(manifest.mutations)}
}

export function createClient(origin: string, token: () => string | Promise<string>) {
  const client = new ReactiveCoreClient(origin, token);
  return {
    query<K extends keyof Queries>(name: K, args: Queries[K]['args'], signal?: AbortSignal) {
      return client.query<Queries[K]['result']>(name, args, signal);
    },
    subscribe<K extends keyof Queries>(name: K, args: Queries[K]['args'], signal: AbortSignal) {
      return client.subscribe<Queries[K]['result']>(name, args, signal);
    },
    mutate<K extends keyof Mutations>(name: K, args: Mutations[K]['args'], key: string, signal?: AbortSignal) {
      return client.mutate<Mutations[K]['result']>(name, args, key, signal);
    },
  };
}
`;
  const previous = await readFile(output, 'utf8').catch((error) => {
    if (error.code !== 'ENOENT') throw error;
    return null;
  });
  if (previous !== null && !previous.startsWith(generated))
    throw new Error('client.ts is not a generated file');
  const temporary = join(directory, `.client-${randomUUID()}.tmp`);
  await writeFile(temporary, content, { flag: 'wx' });
  try {
    await rename(temporary, output);
  } catch (error) {
    await unlink(temporary);
    throw error;
  }
}

function databaseUrl(connection, database) {
  const url = new URL(connection);
  if (database) url.pathname = `/${database}`;
  return url.href;
}

async function connected(connectionString, callback) {
  const client = new pg.Client({
    connectionString,
    connectionTimeoutMillis: 5000,
  });
  await client.connect();
  try {
    return await callback(client);
  } finally {
    await client.end();
  }
}

async function migrations(directory, prefix) {
  const files = (await readdir(directory, { withFileTypes: true }))
    .filter(
      (entry) => entry.isFile() && /^\d{3}_[a-z0-9_]+\.sql$/.test(entry.name),
    )
    .map((entry) => entry.name)
    .sort();
  const versions = new Set(files.map((name) => name.slice(0, 3)));
  if (versions.size !== files.length)
    throw new Error(`Duplicate migration number in ${directory}`);
  return Promise.all(
    files.map(async (name) => {
      const source = await readFile(join(directory, name), 'utf8');
      return {
        name: `${prefix}/${name}`,
        hash: createHash('sha256').update(source).digest('hex'),
        source,
      };
    }),
  );
}

