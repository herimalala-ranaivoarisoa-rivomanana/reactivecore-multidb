async function apply(client, files) {
  const { rows } = await client.query(
    'SELECT name, hash FROM reactivecore_cli.migrations',
  );
  const applied = new Map(rows.map(({ name, hash }) => [name, hash]));
  const lookup = new Map(files.map(({ name, hash }) => [name, hash]));
  for (const [name, hash] of applied) {
    if (
      !lookup.has(name) ||
      (lookup.get(name) !== hash && legacyCoreHashes.get(name) !== hash)
    )
      throw new Error('Applied migrations were changed or removed');
  }
  for (const namespace of ['core/', 'project/']) {
    let pending = false;
    for (const { name } of files.filter((file) =>
      file.name.startsWith(namespace),
    )) {
      if (!applied.has(name)) pending = true;
      else if (pending)
        throw new Error('A migration was inserted before an applied version');
    }
  }
  for (const { name, hash, source } of files.filter(
    (file) => !applied.has(file.name),
  )) {
    const sql = source
      .replace(/^\s*BEGIN;\s*/i, '')
      .replace(/\s*COMMIT;\s*$/i, '');
    await client.query('BEGIN');
    try {
      await client.query(sql);
      await client.query(
        'INSERT INTO reactivecore_cli.migrations VALUES ($1, $2)',
        [name, hash],
      );
      await client.query('COMMIT');
    } catch (error) {
      await client.query('ROLLBACK');
      throw new Error(`Migration failed: ${name}: ${error.message}`);
    }
    console.log(`Applied ${name}`);
  }
}

async function administer(adminUrl, database, name, create, callback) {
  const managed = process.env.RC_PROVISION_EXISTING_DATABASE === '1';

  async function useDatabase(url, fresh) {
    await connected(url, async (client) => {
      await client.query(
        "SELECT pg_advisory_lock(hashtext('reactivecore-cli:database')::bigint)",
      );
      await client.query('SET search_path TO public');
      const marker = await client.query(
        "SELECT to_regclass('reactivecore_cli.project') IS NOT NULL AS found",
      );
      if (!marker.rows[0].found) {
        if (!create || (!fresh && !managed))
          throw new Error('Existing database is not managed by the CLI');
        if (managed) {
          const {
            rows: [state],
          } = await client.query(`
            SELECT EXISTS (
              SELECT FROM pg_namespace
              WHERE nspname NOT IN ('public', 'information_schema')
                AND nspname !~ '^pg_'
              UNION ALL
              SELECT FROM pg_depend
              WHERE refclassid = 'pg_namespace'::regclass
                AND refobjid = 'public'::regnamespace
              UNION ALL
              SELECT FROM pg_extension WHERE extname <> 'plpgsql'
            ) AS occupied
          `);
          if (state.occupied)
            throw new Error(
              'Managed provisioning requires a dedicated empty database',
            );
        }
        await client.query('BEGIN');
        try {
          await client.query(`
            CREATE SCHEMA reactivecore_cli;
            REVOKE ALL ON SCHEMA reactivecore_cli FROM PUBLIC;
            CREATE TABLE reactivecore_cli.project (name text PRIMARY KEY);
            CREATE TABLE reactivecore_cli.migrations (name text PRIMARY KEY, hash text NOT NULL)
          `);
          await client.query(
            'INSERT INTO reactivecore_cli.project VALUES ($1)',
            [name],
          );
          await client.query('COMMIT');
        } catch (error) {
          await client.query('ROLLBACK');
          throw error;
        }
      }
      const project = await client.query(
        'SELECT name FROM reactivecore_cli.project',
      );
      if (project.rowCount !== 1 || project.rows[0].name !== name)
        throw new Error('Database belongs to another project');
      await callback(client);
    });
  }

  if (managed) {
    if (decodeURIComponent(new URL(adminUrl).pathname) !== `/${database}`)
      throw new Error(
        `RC_PROVISION_ADMIN_URL must point to ${database} in existing database mode`,
      );
    return useDatabase(adminUrl, false);
  }

  await connected(databaseUrl(adminUrl, 'postgres'), async (server) => {
    await server.query(
      "SELECT pg_advisory_lock(hashtext('reactivecore-cli:provision')::bigint)",
    );
    const existing = await server.query(
      'SELECT 1 FROM pg_database WHERE datname = $1',
      [database],
    );
    const fresh = existing.rowCount === 0;
    if (fresh) {
      if (!create) throw new Error('Provision the project first');
      await server.query(`CREATE DATABASE "${database}"`);
    }
    await useDatabase(databaseUrl(adminUrl, database), fresh);
  });
}

async function start(command, directory, name, database, manifest) {
  const connection = new URL(env('DATABASE_URL'));
  if (decodeURIComponent(connection.pathname) !== `/${database}`) {
    throw new Error(`DATABASE_URL must point to ${database}`);
  }
  const role = command === 'serve' ? 'reactivecore_app' : 'reactivecore_worker';
  if (decodeURIComponent(connection.username) !== role) {
    throw new Error(`DATABASE_URL must use the ${role} login`);
  }
  const script =
    command === 'serve' ? 'platform-main.js' : 'outbox/outbox.worker.js';
  const runtimeEnv = {
    ...process.env,
    RC_INVALIDATION_CHANNEL:
      process.env.RC_INVALIDATION_CHANNEL ?? `reactivecore:project:${name}`,
  };
  delete runtimeEnv.RC_PROVISION_ADMIN_URL;
  delete runtimeEnv.RC_PROVISION_EXISTING_DATABASE;
  delete runtimeEnv.RC_PROVISION_APP_PASSWORD;
  delete runtimeEnv.RC_PROVISION_WORKER_PASSWORD;
  if (connection.protocol === 'mysql:' && command === 'serve') {
    const { mysqlTables } = await import('./mysql-project.mjs');
    runtimeEnv.RC_MYSQL_TABLES = mysqlTables(manifest).join(',');
  }
  if (command === 'serve') {
    runtimeEnv.RC_APPLICATION_FILE = join(directory, 'application.mjs');
    runtimeEnv.RC_JWT_AUDIENCE ??= `reactivecore:${name}`;
  } else {
    delete runtimeEnv.RC_JWT_DEV_SECRET;
  }
  const server = spawn(
    process.execPath,
    [join(root, 'apps/api/dist', script)],
    {
      stdio: 'inherit',
      env: runtimeEnv,
    },
  );
  const interrupt = () => server.kill('SIGINT');
  const terminate = () => server.kill('SIGTERM');
  process.on('SIGINT', interrupt);
  process.on('SIGTERM', terminate);
  try {
    process.exitCode = await new Promise((resolveExit, reject) => {
      server.once('error', reject);
      server.once('exit', (code, signal) =>
        resolveExit(code ?? (signal === 'SIGINT' ? 130 : 143)),
      );
    });
  } finally {
    process.off('SIGINT', interrupt);
    process.off('SIGTERM', terminate);
  }
}

async function main() {
  const [command, path, id, ...extra] = process.argv.slice(2);
  if (
    !path ||
    !['init', 'codegen', 'provision', 'tenant', 'serve', 'worker'].includes(
      command,
    ) ||
    (command === 'tenant' ? !id || extra.length : id !== undefined)
  ) {
    throw new Error(
      'Usage: reactivecore <init|codegen|provision|tenant|serve|worker> <directory> [tenant-uuid]',
    );
  }
  const directory = resolve(path);
  const manifestPath = join(directory, 'project.json');
  if (command === 'init') {
    const name = basename(directory);
    if (!format.test(name))
      throw new Error(
        'Use a lowercase project slug with at most 40 characters',
      );
    await mkdir(directory);
    for (const entry of await readdir(template)) {
      await cp(join(template, entry), join(directory, entry), {
        recursive: true,
        force: false,
        errorOnExist: true,
      });
    }
    const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
    manifest.name = name;
    await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
    await codegen(directory, manifest);
    console.log(`Created ${name}`);
    return;
  }
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  const name = manifest.name;
  if (typeof name !== 'string' || !format.test(name))
    throw new Error('Invalid project slug');
  const database = `reactivecore_${name.replaceAll('-', '_')}`;

  if (command === 'codegen') return codegen(directory, manifest);
  if (command === 'serve' || command === 'worker')
    return start(command, directory, name, database, manifest);

  const admin = env('RC_PROVISION_ADMIN_URL');
  if (command === 'tenant' && !uuid.test(id))
    throw new Error('Expected a tenant UUID');
  if (new URL(admin).protocol === 'mysql:') {
    const { administerMysql } = await import('./mysql-project.mjs');
    return administerMysql({
      root,
      directory,
      manifest,
      database,
      admin,
      command,
      id,
    });
  }
  if (command === 'tenant') {
    return administer(admin, database, name, false, (client) =>
      client.query(
        'INSERT INTO public.tenants (id, name) VALUES ($1, $2) ON CONFLICT (id) DO NOTHING',
        [id, 'Project tenant'],
      ),
    );
  }

  const files = [
    ...(await migrations(join(root, 'db/migrations'), 'core')),
    ...(await migrations(join(directory, 'migrations'), 'project')),
  ];
  const appPassword = process.env.RC_PROVISION_APP_PASSWORD;
  const workerPassword = process.env.RC_PROVISION_WORKER_PASSWORD;
  if (Boolean(appPassword) !== Boolean(workerPassword)) {
    throw new Error(
      'Supply both role passwords when bootstrapping an empty cluster',
    );
  }
  await administer(admin, database, name, true, async (client) => {
    await apply(client, files);
    await client.query(`REVOKE CONNECT ON DATABASE "${database}" FROM PUBLIC`);
    await client.query(
      `GRANT CONNECT ON DATABASE "${database}" TO reactivecore_app, reactivecore_worker`,
    );
    if (appPassword && workerPassword) {
      await client.query('BEGIN');
      try {
        for (const [role, password] of [
          ['reactivecore_app', appPassword],
          ['reactivecore_worker', workerPassword],
        ]) {
          const {
            rows: [entry],
          } = await client.query(
            'SELECT rolcanlogin FROM pg_roles WHERE rolname = $1',
            [role],
          );
          if (entry.rolcanlogin) continue;
          const {
            rows: [statement],
          } = await client.query(
            "SELECT format('ALTER ROLE %I LOGIN PASSWORD %L', $1::text, $2::text) AS sql",
            [role, password],
          );
          await client.query(statement.sql);
        }
        await client.query('COMMIT');
      } catch {
        await client.query('ROLLBACK');
        throw new Error('Could not initialize PostgreSQL login credentials');
      }
    }
  });
  console.log(`Provisioned ${database}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
